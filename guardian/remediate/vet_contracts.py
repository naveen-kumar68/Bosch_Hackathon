"""Module-owned detector binding contracts, pending the lead's shared API."""

from collections.abc import Callable
from dataclasses import dataclass, field

from pydantic import Field

from guardian.remediate.models import EvidenceId, Model


class VetPolicy(Model):
    min_release_age_days: int = Field(default=7, ge=0)
    min_popular_names: int = Field(default=5000, ge=1)
    trusted_publishers: dict[str, list[str | int]] = Field(default_factory=dict)
    evidence_ids: list[EvidenceId] = Field(min_length=1)


@dataclass(frozen=True)
class CapturedVersion:
    ecosystem: str
    package: str
    version: str
    metadata: dict
    metadata_evidence_ids: tuple[str, ...]
    history: list[dict] | None = None
    history_evidence_ids: tuple[str, ...] = ()
    osv_document: dict | None = None
    osv_evidence_ids: tuple[str, ...] = ()
    artifact: bytes | None = field(default=None, repr=False)
    registry_sha256: str | None = None
    artifact_evidence_ids: tuple[str, ...] = ()
    checksum_evidence_ids: tuple[str, ...] = ()


@dataclass(frozen=True)
class DetectorBindings:
    """Bootstrap injects the existing functions; Module 2 never copies their rules.

    semgrep is a lead-owned wrapper (directory, *, proc_macro) -> (JSON,evidence ID)
    around the existing scanner with pinned rules/image and recorder already bound.
    All callbacks are trusted code, never selected or generated by the LLM.
    """

    parse_osv: Callable
    metadata_changes: Callable
    new_dependencies: Callable
    typosquat_candidates: Callable
    verified_extract: Callable
    inspect_sources: Callable
    capability_diff: Callable
    semgrep: Callable
    evidence_exists: Callable
